"""Write docs/parts_list.md and docs/kinematics.md from the live model."""
import os, sys, json
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
import trimesh
from robo_rex import assembly as AS, kinematics as K, params as P, validate as V

DOCS = os.path.join(AS.ROOT, "docs")
STOPS = {
    "head": "ball: skull face meets dorsal plate / dino: V-notch faces meet",
    "jaw": "skull post in a C-gap around the jaw pin (both ends)",
    "tail1": "ball: faces meet / dino: V-notch faces meet",
    "tail2": "ball: faces meet / dino: V-notch faces meet",
    "tail3": "ball: faces meet / dino: V-notch faces meet",
    "arm_L": "torso shoulder post in arm C-ring", "arm_R": "torso shoulder post in arm C-ring",
    "thigh_L": "torso hip post in thigh C-ring", "thigh_R": "torso hip post in thigh C-ring",
    "shin_L": "thigh bar in shin C-ring (dino stop carries standing load)",
    "shin_R": "thigh bar in shin C-ring (dino stop carries standing load)",
    "panel_L": "pole-cap lug in ear slot (both ends)", "panel_R": "pole-cap lug in ear slot (both ends)",
}


def parts_list():
    man = json.load(open(os.path.join(AS.ROOT, "output", "reports", "print_manifest.json")))
    L = ["# Parts list", "", "Generated by `scripts/generate_docs.py` from the CAD model. Mass is an "
         "estimate for PLA at 1.24 g/cm3 with 3 walls (1.2 mm skin) and 20 % infill; pins and "
         "axles should be printed at 100 % infill.", "",
         "| # | STL file | qty | description | est. mass each (g) | print size (mm) | needs supports |",
         "|---|---|---|---|---|---|---|"]
    tot = 0.0
    i = 0
    for name, v in man.items():
        if v["kind"] == "calibration":
            continue
        i += 1
        m = trimesh.load(os.path.join(AS.ROOT, v["file"]), force="mesh")
        g = V.part_mass(m) if v["kind"] == "part" else m.volume * 1.24e-3
        tot += g * v["qty"]
        sup = "yes (tree, from bed)" if v["overhang_area_mm2"] > 150 else "no"
        L.append(f"| {i} | `{v['file']}` | {v['qty']} | {v['description']} | {g:.1f} | "
                 f"{' x '.join(str(e) for e in v['extents_mm'])} | {sup} |")
    L += ["", f"**Total printed parts: {sum(v['qty'] for v in man.values() if v['kind'] != 'calibration')}, "
          f"estimated filament {tot:.0f} g** (plus supports, brims and calibration coupons).", "",
          "No purchased hardware: every pin, axle, latch and hinge is printed.", "",
          "## Calibration coupons (print first)", "", "| file | purpose |", "|---|---|"]
    purpose = {
        "cal_pin_gauge": "running-hole clearance 0.2-0.6 mm (top row) and D-hole press fit -0.1..+0.2 mm (bottom row); notches = column",
        "cal_test_pins": "four D4 test pins for the gauge",
        "cal_knuckle_fork": "real-size knuckle fork (head/tail joints)",
        "cal_knuckle_tongue": "real-size knuckle tongue; check rotation friction",
        "cal_latch_channel": "flat replica of the belly latch channel + detents",
        "cal_latch_slider": "matching slider",
        "cal_latch_notch": "panel notch section the slider locks into",
        "cal_axle_stub": "short main-axle section with D-key and cap socket",
        "cal_axle_block": "D-keyed press block (torso hub fit)",
        "cal_axle_ear": "front-panel ear ring: running fit on the axle + pole-cap counterbore",
    }
    for name, v in man.items():
        if v["kind"] == "calibration":
            L.append(f"| `{v['file']}` | {purpose.get(name, '')} |")
    open(os.path.join(DOCS, "parts_list.md"), "w").write("\n".join(L) + "\n")


def kinematics():
    L = ["# Kinematic model", "",
         "Generated from `src/robo_rex/kinematics.py`. Frame: origin = ball centre, +X forward, "
         "+Y left, +Z up (ball frame, fixed to the torso). **Every revolute axis is parallel to +Y**, "
         "so the mechanism is planar. Positive angles rotate +X toward +Z. Each part is modelled at "
         "q = 0; the table gives q in each mode. Pivots are listed with all ancestors at their own q = 0.", "",
         f"In dinosaur mode the whole toy is pitched nose-up by {P.DINO_PITCH} deg so the tail tip "
         "rests on the ground (tripod stance). That pitch is a world orientation, not a joint.", "",
         "| joint | parent | pivot x, z (mm) | range (deg) | dino | ball | mechanical stops |",
         "|---|---|---|---|---|---|---|"]
    for j, d in K.JOINTS.items():
        L.append(f"| {j} | {d['parent']} | {d['pivot'][0]:.2f}, {d['pivot'][1]:.2f} | "
                 f"{d['range'][0]:g} .. {d['range'][1]:g} | {d['dino']:g} | {d['ball']:g} | {STOPS[j]} |")
    L += ["", f"Latch sliders are prismatic along +/-Y: travel {P.LATCH_TRAVEL} mm, locked in ball mode, "
          "with a 0.3 mm detent bump limiting outward travel.", "",
          "## Transformation sequence (dino -> ball; reverse it for ball -> dino)", ""]
    for i, (name, tgt) in enumerate(K.SEQUENCE, 1):
        L.append(f"{i}. **{name}**: " + ", ".join(f"{k} -> {v:g}" for k, v in tgt.items()))
    L += ["", "The two-stage leg fold (swing back while bending, then fold the knee) came from a "
          "breadth-first search over a hip/knee occupancy grid built from the real meshes "
          "(`scripts/plan_leg_path.py`). A straight hip+knee interpolation drives the foot through the "
          "opened armour panel."]
    open(os.path.join(DOCS, "kinematics.md"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    os.makedirs(DOCS, exist_ok=True)
    parts_list()
    kinematics()
    print("docs written")
