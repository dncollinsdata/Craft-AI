"""Run every software check and write output/reports/validation_report.{md,json}.

Exit code is non-zero if any hard check fails.
"""
import os, sys, json, time
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
import numpy as np
import trimesh
from robo_rex import assembly as AS, validate as V, kinematics as K, params as P, printing as PR

REP = os.path.join(AS.ROOT, "output", "reports")


def jsonable(o):
    if isinstance(o, (np.generic,)):
        return o.item()
    if isinstance(o, tuple):
        return list(o)
    return str(o)


def stl_checks():
    """Re-load every exported STL and check it as a slicer would."""
    man = json.load(open(os.path.join(REP, "print_manifest.json")))
    out = {}
    for name, info in man.items():
        m = trimesh.load(os.path.join(AS.ROOT, info["file"]), force="mesh")
        bodies = m.split(only_watertight=False)
        out[name] = dict(watertight=bool(m.is_watertight), winding=bool(m.is_winding_consistent),
                         nonmanifold_edges=PR.nonmanifold_edges(m), bodies=len(bodies),
                         fits_ender3=PR.fits_bed(m), volume_cm3=round(m.volume / 1000, 2),
                         overhang_mm2=info["overhang_area_mm2"], qty=info["qty"], kind=info["kind"])
    return out


def main():
    t0 = time.time()
    R = {}
    print("part integrity ...")
    R["integrity"] = {n: V.part_integrity(n) for n in AS.ORDER}
    print("exported STL checks ...")
    R["stl"] = stl_checks()
    print("static poses ...")
    R["overlaps_dino"] = V.static_overlaps("dino")
    R["overlaps_ball"] = V.static_overlaps("ball")
    R["outside_sphere_ball"] = V.envelope_ball()
    print("transformation path ...")
    hits, n = V.path_check(max_step_deg=1.0)
    R["path"] = dict(states=n, max_step_deg=1.0, collisions=hits)
    R["jaw_sweep"] = V.jaw_sweep()
    print("stops ...")
    R["stops"] = V.stop_check()
    print("clearances ...")
    R["clearance_ball"] = V.clearances("ball")
    R["clearance_dino"] = V.clearances("dino")
    print("standing ...")
    R["standing"] = V.standing()
    print("rolling ...")
    R["rolling"] = V.rolling()
    R["runtime_s"] = round(time.time() - t0, 1)

    hard = {
        "all parts valid single solids": all(v["brep_valid"] and v["solids"] == 1 for v in R["integrity"].values()),
        "all part meshes watertight, 0 non-manifold edges": all(v["watertight"] and v["nonmanifold_edges"] == 0 for v in R["integrity"].values()),
        "all exported STLs watertight": all(v["watertight"] and v["nonmanifold_edges"] == 0 for v in R["stl"].values()),
        "all STLs fit Ender 3 bed": all(v["fits_ender3"] for v in R["stl"].values()),
        "no interference in dino mode": not R["overlaps_dino"],
        "no interference in ball mode": not R["overlaps_ball"],
        "ball mode inside 100 mm sphere": not R["outside_sphere_ball"],
        "collision-free transformation path": not hits,
        "jaw opens 0..-30 deg without contact": not R["jaw_sweep"],
        "every joint has working hard stops": all(v["stops_ok"] for v in R["stops"].values()),
        "dino stands (CoM inside support, margin > 2 mm)": R["standing"]["stable"],
        "only feet + tail tip touch the ground": set(R["standing"]["ground_contacts"]) <= {"shin_L", "shin_R", "tail3"},
        "knee stops carry standing load": R["standing"]["knee_stop_carries"],
        "rolling spine band >= 95 % at full radius": R["rolling"]["sagittal_frac_ge_49"] >= 0.95,
    }
    R["hard_checks"] = hard
    json.dump(R, open(os.path.join(REP, "validation_report.json"), "w"), indent=1, default=jsonable)
    write_md(R)
    print("\n".join(f"[{'PASS' if v else 'FAIL'}] {k}" for k, v in hard.items()))
    return 0 if all(hard.values()) else 1


def write_md(R):
    L = ["# ROBO REX BALL - software validation report", "",
         f"Generated by `scripts/validate_geometry.py` (runtime {R['runtime_s']} s).", "",
         "**Nothing in this report is a physical test.** Every result below comes from CAD "
         "geometry, mesh booleans and a simple mass model. See the last section for what must "
         "be verified on a real printer.", "", "## Summary of hard checks", ""]
    L += [f"- {'PASS' if v else '**FAIL**'}: {k}" for k, v in R["hard_checks"].items()]
    L += ["", "## Part integrity (B-rep + mesh)", "",
          "| part | valid | solids | watertight | non-manifold edges | volume cm3 | wall p1 (mm) | faces <1.2 mm |",
          "|---|---|---|---|---|---|---|---|"]
    for n, v in R["integrity"].items():
        L.append(f"| {n} | {v['brep_valid']} | {v['solids']} | {v['watertight']} | {v['nonmanifold_edges']} | "
                 f"{v['volume_cm3']} | {v['thick_p01']} | {100 * v['thick_frac_below_1p2']:.1f} % |")
    L += ["", "Wall thickness is sampled by casting rays inward from 1200 random surface points per part. "
          "The 1st-percentile value picks up deliberate features (0.6 mm decorative grooves, chamfer "
          "steps, hole edges), not structural walls. Structural minimums by design: front panels 2.8 mm, "
          "rear shell 2.0 mm, hinge ears 2.8 mm under the pole counterbore, tongue walls >= 2.25 mm "
          "around pins.", "",
          "## Exported STL files", "", "| file | qty | watertight | bodies | fits Ender 3 | overhang mm2 |",
          "|---|---|---|---|---|---|"]
    for n, v in R["stl"].items():
        L.append(f"| {n} | {v['qty']} | {v['watertight']} | {v['bodies']} | {v['fits_ender3']} | {v['overhang_mm2']} |")
    s = R["standing"]
    L += ["", "## Static poses", "",
          f"- Dino mode interferences: {R['overlaps_dino'] or 'none'}",
          f"- Ball mode interferences: {R['overlaps_ball'] or 'none'}",
          f"- Material outside the 100 mm sphere in ball mode: {R['outside_sphere_ball'] or 'none'}",
          f"- Dino size: {s['length_mm']} mm long x {s['width_mm']} mm wide x {s['height_mm']} mm tall",
          "", "## Transformation path", "",
          f"{R['path']['states']} intermediate states sampled with at most {R['path']['max_step_deg']} deg "
          f"per joint per step through the sequence in `kinematics.SEQUENCE`. Collisions found: "
          f"{len(R['path']['collisions'])}. Jaw opening sweep (dino mode, 1 deg steps): "
          f"{len(R['jaw_sweep'])} collisions.", "",
          "## Mechanical stops", "", "| joint | range (deg) | free at both ends | stop engages at |",
          "|---|---|---|---|"]
    for j, v in R["stops"].items():
        L.append(f"| {j} | {v['range']} | {v['free_at_lo'] and v['free_at_hi']} | "
                 f"{v['stop_lo_at']} / {v['stop_hi_at']} |")
    L += ["", "## Clearances (minimum gap, mm)", "", "| pair | ball | dino |", "|---|---|---|"]
    for k in R["clearance_ball"]:
        L.append(f"| {k} | {R['clearance_ball'][k]} | {R['clearance_dino'][k]} |")
    L += ["", "Gaps of ~0.1 mm are hard stops sitting 1 deg from contact at the end of their range "
          "(by design). The 0.0 mm skull/jaw value is a 0.007 mm3 tessellation-level touch at the "
          "closed-jaw stop. A value of 5.0 means 'more than 5 mm'.", "",
          "## Standing (dino mode)", ""]
    L += [f"- {k}: {v}" for k, v in s.items()]
    r = R["rolling"]
    L += ["", "## Rolling (ball mode)", ""] + [f"- {k}: {v}" for k, v in r.items()]
    L += ["", "Interpretation: the sagittal 'spine' band (head, dorsal plate, tail, belly) is at the full "
          "50 mm radius, so a forward roll runs on a near-continuous great circle. Gaps there are the "
          "1 deg seams between parts and the two radial bridge-pin holes (filled by pins, which are "
          "not in the collision model). The rear haunch shell is 3.2 mm smaller in radius than the "
          "front panels because the panels nest over it in dino mode, so a sideways roll has a "
          "3.2 mm step at the seam. The ball's centre of mass sits ~3 mm off-centre, so it will "
          "settle in a preferred orientation when it stops.", "",
          "## Requires physical printing (not verified here)", "",
          "- Pin fits: running clearance (params.CLR) and D-pin press fits. Print `cal_pin_gauge` + `cal_test_pins` first.",
          "- Friction needed to hold the head up in dino mode. Its stop is on the unfold side, so gravity "
          "works against friction only (about 2-3 N*mm). Tune with `cal_knuckle_*`.",
          "- Latch slider feel and the 0.3 mm detent click (`cal_latch_*`).",
          "- Axle press fit in the torso and pole-cap retention (`cal_axle_*`).",
          "- Real print accuracy of the 100 mm shells, warping of the large thin panels, and whether the hinge-ear supports clean up.",
          "- Real standing stability on a smooth table (friction, play in joints) and real rolling behaviour.",
          "- Strength and durability of the 4.6 mm arms, the 3 mm jaw pin and the 2 mm rear shell."]
    open(os.path.join(REP, "validation_report.md"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    sys.exit(main())
